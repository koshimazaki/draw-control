/**
 * A setup saved on Example 4 (the drone between pillars), called from smoke-beat-path.mjs. Examples
 * 3 and 4 left the page's switcher on 15 Nov 2026; their scripts stay in examples/scripts/. A setup
 * saved on one names its example as the track ("drone"): loaded on Example 2, the page switches to
 * Your own and loads it there as saved, with a note. The drone opens on its rig's start (the
 * script's rig: line), isometric and high, then orbit, top and side, on its 6-bar laidback groove,
 * and plays; Example 1 and back to Your own keeps it. Any console error or warning fails the run.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const DRONE = new URL("../examples/scripts/beat-path-ex4-drone.txt", import.meta.url);
const GROOVE = "generated-laidback-100-6bars.wav";

/**
 * A setup file of a script-only example on its 100 BPM groove, built in the page (scriptState and
 * setupJson from the dev server's modules) and written to `path`: `track` is the id its state names
 * ("drone", "car" as saved before 15 Nov 2026; "laidback", "laidback-6" since).
 */
export async function grooveSetup(page, script, track, groove, path) {
  const file = JSON.parse(await page.evaluate(async ([text, groove]) => {
    const { scriptState } = await import("/src/beat-path/examples.ts");
    const { setupJson } = await import("/src/beat-path/setup-file.ts");
    return setupJson(scriptState(text, 100), { name: groove, licence: "generated by motion-studio (MIT)", bpm: 100, offsetSeconds: 0.09, lengthSeconds: 15 });
  }, [readFileSync(script, "utf8"), groove]));
  // An old save named the example itself; the page no longer prints that id, so it is written into the file as such a save had it.
  file.state.track = track;
  writeFileSync(path, JSON.stringify(file, null, 2) + "\n");
  return file;
}

export async function smokeBeatPathRetired(browser, base, { fail, OUT, SHOTS }) {
  const dir = `${OUT}setup/`;
  mkdirSync(dir, { recursive: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  const errors = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("console", m => { if (m.type() === "error" || m.type() === "warning") errors.push(`${m.type()}: ${m.text()}`); });
  await page.goto(`${base}/path.html`);
  await page.waitForFunction(() => window.__beatPath?.recipe().audio?.name === "neon-rain-loop.mp3", null, { timeout: 30_000 });
  // The setup as the page saved it on Example 4 before it left: the drone script's state, its track named "drone".
  const path = `${dir}example-4-setup.json`;
  const saved = (await grooveSetup(page, DRONE, "drone", GROOVE, path)).state;

  // Loaded while Example 2 shows.
  await page.click('[data-control="example"] [data-value="1"]');
  await page.waitForFunction(() => window.__beatPath.slot() === "1" && window.__beatPath.trackName() === "drum-n-bass.mp3", null, { timeout: 30_000 });
  await page.evaluate(() => { document.getElementById("status").textContent = ""; });
  await page.setInputFiles("#setupFile", path);
  await page.waitForFunction(() => /^(Loaded the setup|Not loaded)/.test(document.getElementById("status").textContent), null, { timeout: 60_000 })
    .catch(() => fail("a setup saved on Example 4: the page said nothing after loading"));
  await page.waitForFunction(g => window.__beatPath.trackName() === g, GROOVE, { timeout: 30_000 }).catch(() => {});
  const look = () => page.evaluate(() => ({
    slot: window.__beatPath.slot(), on: document.querySelector('[data-control="example"] button.on')?.dataset.value, status: document.getElementById("status").textContent,
    r: window.__beatPath.recipe(), cam0: window.__beatPath.cameraAt(0), track: window.__beatPath.trackName(), state: window.__beatPath.state(),
  }));
  const got = await look();
  const ranges = got.r.camera?.segments.map(s => s.modes.join("+")).join(" ");
  console.log(`draw control retired: a setup saved on Example 4, loaded on Example 2: slot ${got.slot} (switcher on ${got.on}); "${got.status}"; ranges ${ranges}; rig ${got.r.camera?.distance} m, ${got.r.camera?.height} m, fov ${got.r.camera?.fov}, yaw ${got.r.camera?.startYaw}; frame 0 camera at ${got.cam0.position.map(v => v.toFixed(2)).join(", ")}; track ${got.track}`);
  if (got.slot !== "own" || got.on !== "own") fail(`a setup saved on Example 4 did not load as Your own (slot ${got.slot}, switcher on ${got.on})`);
  if (!/^Loaded the setup/.test(got.status) || !/Example 4 .*no longer on the page: loaded as Your own/.test(got.status)) fail(`a setup saved on Example 4 did not say it loaded as Your own ("${got.status}")`);
  if (got.r.figure?.shape !== "flyer" || got.r.camera?.startYaw !== 45) fail(`the drone did not open on its rig (figure ${got.r.figure?.shape}, yaw ${got.r.camera?.startYaw})`);
  if (ranges !== "threeQuarter orbit top side") fail(`the drone's camera ranges are ${ranges}, not threeQuarter orbit top side`);
  if (!(got.cam0.position[1] > 5)) fail(`the drone's frame 0 camera is at ${got.cam0.position[1]} m, not above 5 m`);
  if (got.track !== GROOVE || got.state.track !== "laidback-6") fail(`the drone plays ${got.track} (track ${got.state.track}), not its 6-bar laidback groove`);
  if (JSON.stringify(got.state.subject) !== JSON.stringify(saved.subject) || JSON.stringify(got.state.cameraLane) !== JSON.stringify(saved.cameraLane) || JSON.stringify(got.state.rig) !== JSON.stringify(saved.rig))
    fail("the setup saved on Example 4 did not load with its path, camera lane and rig intact");
  await page.click("#play");
  await page.waitForTimeout(600);
  if (!(await page.evaluate(() => window.__beatPath.playing()))) fail("the drone loaded as Your own does not play");
  await page.click("#play");
  await page.screenshot({ path: `${SHOTS}beat-path-retired-example-4.png` });

  // Example 1 and back: Your own keeps the drone, and its groove comes back with it.
  await page.click('[data-control="example"] [data-value="0"]');
  await page.waitForFunction(() => window.__beatPath.slot() === "0" && window.__beatPath.trackName() === "neon-rain-loop.mp3", null, { timeout: 30_000 });
  await page.click('[data-control="example"] [data-value="own"]');
  await page.waitForFunction(g => window.__beatPath.slot() === "own" && window.__beatPath.trackName() === g, GROOVE, { timeout: 30_000 })
    .catch(() => fail("Your own did not bring the drone's groove back"));
  const back = await look();
  console.log(`draw control retired: Example 1 and back to Your own: figure ${back.r.figure?.shape}, yaw ${back.r.camera?.startYaw}, track ${back.track}`);
  if (back.r.camera?.startYaw !== 45 || JSON.stringify(back.state.subject) !== JSON.stringify(saved.subject)) fail("Your own did not keep the drone after a switch");
  if (errors.length) fail(`retired setup page errors: ${errors.join(" | ")}`);
  await page.close();
}
