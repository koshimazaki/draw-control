/**
 * Each example's music: one small table. Examples 1 and 2 play a file, the owner's own music in
 * packages/studio/public/tracks/; Examples 3 and 4 play a groove generated in the browser by the
 * in-repo drum synth, at 100 BPM (they share the laidback groove at different lengths). An entry with a `file` ("tracks/your-file.mp3") is fetched and analysed like a dropped
 * track; its `groove` and `bars` are the fallback when the file cannot load, and its "# track:"
 * comment names the file (script.ts), so a script tells it apart from the grooves.
 */
import type { GrooveStyle } from "@motion-studio/core";

/**
 * `grid`: the music's beat grid, given instead of estimated. Example 1's guide starts at the file's
 * own start (beat 0 at 0 s, where the analysis puts it at 0.081 s), so the finish step
 * (scripts/finish-clip.mjs) lays the original audio on a generated clip with no offset. It holds on
 * the fallback groove too, so the moves stay put when the file cannot load.
 * Example 2's drum and bass loop reads 69.7 BPM to the estimator; its kicks and snares sit on a 174 BPM grid (32 beats,
 * eight bars, in its 11.04 s, every strong hit within 15 ms of a half beat), so its grid is given too.
 */
export type ExampleTrack = { name: string; groove: GrooveStyle; bars: number; file?: string; grid?: { bpm: number; offsetSeconds: number }; licence: string };

