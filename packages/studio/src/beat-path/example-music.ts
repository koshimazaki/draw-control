/**
 * An example's music as raw samples, for the Gallery (the editor loads it through page.ts
 * `useExampleTrack`, the same rule): its file when tracks.ts gives one, else the in-repo drum
 * synth. A file that fails to load falls back to the synth groove, as the editor does, under a
 * generated name and licence (`musicIdentity`): the guide never credits a file it does not contain.
 */
import { GROOVES, grooveTimes, synthDrums } from "@motion-studio/core";
import { TRACKS, type TrackId } from "./tracks";
import { DECODE_RATE } from "../audio";

export type ExampleMusic = { channels: Float32Array[]; sampleRate: number; fromFile: boolean };

/** The example's generated groove (tracks.ts `groove` and `bars`). */
export function synthMusic(id: TrackId): ExampleMusic {
  const t = TRACKS[id], seconds = 0.1 + t.bars * 4 * 60 / GROOVES[t.groove].bpm + 0.5;
  return { channels: [synthDrums(grooveTimes(t.groove, t.bars, 0.1), seconds)], sampleRate: 44100, fromFile: false };
}

/**
 * The name and licence the music goes out under: the example's own, unless its file could not load
 * and the synth groove plays instead ("generated-straight-120.wav", MIT).
 */
export function musicIdentity(id: TrackId, fromFile: boolean): { name: string; licence: string } {
  const t = TRACKS[id];
  if (!t.file || fromFile) return { name: t.name, licence: t.licence };
  return { name: `generated-${t.groove}-${GROOVES[t.groove].bpm}.wav`, licence: "generated by motion-studio (MIT)" };
}

const cache = new Map<TrackId, Promise<ExampleMusic>>();

/** The example's music: its file, decoded once per page, or the synth groove. */
export function exampleMusic(id: TrackId, base = document.baseURI): Promise<ExampleMusic> {
  let m = cache.get(id);
  if (!m) { m = load(id, base); cache.set(id, m); }
  return m;
}

async function load(id: TrackId, base: string): Promise<ExampleMusic> {
  const file = TRACKS[id].file;
  if (!file) return synthMusic(id);
  try {
    const res = await fetch(new URL(file, base));
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const buffer = await new OfflineAudioContext(1, 1, DECODE_RATE).decodeAudioData(await res.arrayBuffer());
    const channels = Array.from({ length: buffer.numberOfChannels }, (_, i) => buffer.getChannelData(i).slice());
    return { channels, sampleRate: buffer.sampleRate, fromFile: true };
  } catch { return synthMusic(id); }
}
