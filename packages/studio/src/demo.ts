/**
 * The first-run demo, with nothing from outside the repo: a drum track generated in the
 * browser (the same synth as `npm run drums`, 8 bars at 120 BPM, licence-clean) and the
 * shot script `examples/scripts/glide-path.txt` (a glide on a path, locked to the kicks,
 * the camera following and then flying its own path), shown through the camera rig.
 */
import { encodeWav, patternTimes, synthDrums } from "@motion-studio/core/internal";
import demoScript from "../../../examples/scripts/glide-path.txt?raw";

export const DEMO_TRACK_NAME = "demo-drums-120.wav";
export const DEMO_LICENCE = "generated by motion-studio (MIT)";

export type DemoHost = {
  useTrack(file: File): Promise<void>;
  fitToTrack(): void;
  applyScript(script: string): void;
  showRig(): void;
  setLicence(text: string): void;
};

/** The demo drum track's samples: 8 bars at 120 BPM, first hit at 0.1 s, mono at 44.1 kHz. */
export function demoDrums(): { samples: Float32Array; sampleRate: number; seconds: number } {
  const seconds = 0.1 + 8 * 4 * 60 / 120 + 0.5;
  return { samples: synthDrums(patternTimes(120, 8, 0.1), seconds), sampleRate: 44100, seconds };
}

export async function loadDemo(host: DemoHost) {
  const { samples, sampleRate, seconds } = demoDrums();
  const wav = encodeWav([samples], sampleRate, 0, seconds);
  host.setLicence(DEMO_LICENCE);
  await host.useTrack(new File([wav as BlobPart], DEMO_TRACK_NAME, { type: "audio/wav" }));
  host.fitToTrack();
  host.applyScript(demoScript);
  host.showRig();
}
