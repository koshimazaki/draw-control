/** An example whose music file cannot load (example-music.ts): the generated groove, under its own name and licence. */
import { afterEach, describe, expect, it, vi } from "vitest";
import { exampleMusic, musicIdentity, synthMusic } from "../src/beat-path/example-music";
import { EXAMPLE_TRACKS } from "../src/beat-path/tracks";

afterEach(() => vi.unstubAllGlobals());

describe("a music file that fails to load", () => {
  it("falls back to the synth groove, never named or licensed as the file", async () => {
    vi.stubGlobal("fetch", vi.fn(async () => { throw new Error("offline"); }));
    const m = await exampleMusic("flyer", "http://localhost/");
    expect(m.fromFile).toBe(false);
    expect(m.channels[0].length).toBe(synthMusic("flyer").channels[0].length);
    const named = musicIdentity("flyer", m.fromFile);
    expect(named).toEqual({ name: "generated-straight-120.wav", licence: "generated by motion-studio (MIT)" });
    expect(named.name).not.toBe(EXAMPLE_TRACKS.flyer.name);
  });
  it("keeps the file's own name and licence when it loads, and a groove example's always", () => {
    expect(musicIdentity("flyer", true)).toEqual({ name: "neon-rain-loop.mp3", licence: EXAMPLE_TRACKS.flyer.licence });
    expect(musicIdentity("car", false)).toEqual({ name: EXAMPLE_TRACKS.car.name, licence: EXAMPLE_TRACKS.car.licence });
    expect(musicIdentity("runner", false)).toEqual({ name: "generated-drive-140.wav", licence: "generated by motion-studio (MIT)" });
  });
});

describe("the Gallery on the fallback groove", () => {
  it("refits the lanes to the groove's tempo, as the editor does, so they run to the recipe's end", async () => {
    vi.stubGlobal("document", { baseURI: "http://localhost/" });
    vi.stubGlobal("fetch", vi.fn(async () => { throw new Error("offline"); }));
    const { exampleRecipe } = await import("../src/beat-path/gallery");
    const { s, recipe, music } = await exampleRecipe(0);
    expect(music.fromFile).toBe(false);
    expect(recipe.durationBeats).toBeGreaterThan(26);
    expect(s.cameraLane.at(-1)!.to).toBe(recipe.durationBeats);
    expect(s.character.at(-1)!.to).toBe(recipe.durationBeats);
    const last = recipe.camera!.segments.at(-1)!;
    expect(last.toBeat).toBe(recipe.durationBeats);
    expect(last.modes).toEqual(["top", "pushIn"]);
  });
});
